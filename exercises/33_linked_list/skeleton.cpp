#include <bits/stdc++.h>
using namespace std;

struct ListNode {
  int val;
  ListNode* next;

  ListNode(int v) : val(v), next(nullptr) {}
};

ListNode* reverse_list(ListNode* head) { return head; }

ListNode* merge_sorted(ListNode* a, ListNode* b) { return a; }

ListNode* middle(ListNode* head) { return head; }

ListNode* remove_nth_from_end(ListNode* head, int n) { return head; }

ListNode* cycle_start(ListNode* head) { return nullptr; }

bool is_palindrome(ListNode* head) { return false; }
